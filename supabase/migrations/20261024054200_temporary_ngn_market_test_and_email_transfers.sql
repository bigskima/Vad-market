CREATE OR REPLACE FUNCTION public.pool_quote(p_instrument_public_id uuid, p_outcome_code text, p_amount numeric)
 RETURNS jsonb
 LANGUAGE plpgsql
 SECURITY DEFINER
 SET search_path TO ''
AS $function$
declare
  acct public.user_accounts;
  instrument market.instruments;
  outcome market.outcomes;
  total_pool numeric(38,18):=0;
  outcome_pool numeric(38,18):=0;
  fee numeric(38,18):=0;
  fee_pv bigint;
  est_gross numeric(38,18):=0;
  est_settlement_fee numeric(38,18):=0;
  est_pv bigint;
  v_asset_code text;
  v_test_credit_active boolean:=false;
begin
  acct:=private.require_active_account();
  select * into instrument from market.instruments where public_id=p_instrument_public_id;
  if instrument.id is null then raise exception 'Market not found' using errcode='P0002'; end if;
  if instrument.liquidity_model<>'POOL' then raise exception 'This market does not use pooled staking' using errcode='P0001'; end if;
  if instrument.status<>'OPEN' or instrument.opened_at is null or instrument.opened_at>statement_timestamp() or (instrument.closed_at is not null and instrument.closed_at<=statement_timestamp()) then raise exception 'Market is not open' using errcode='P0001'; end if;
  select a.code into v_asset_code from public.assets a where a.id=instrument.asset_id and a.status='ACTIVE';
  select exists(
    select 1 from public.temporary_ngn_test_credit_grants g
    where g.user_id=auth.uid() and g.asset_id=instrument.asset_id and g.status='ACTIVE'
  ) into v_test_credit_active;
  if v_asset_code='NGN' and not coalesce((select gate.allowed from public.can_access_ngn_services() gate limit 1),false) then
    raise exception 'NGN service requires current location verification. Verify your current location and try again.' using errcode='42501';
  end if;
  if not private.trade_access_satisfies(auth.uid(),acct.country_code,instrument.asset_id) then
    if not (
      v_asset_code='NGN'
      and v_test_credit_active
      and private.service_available('trading',auth.uid())
      and private.asset_available_in_country(acct.country_code,instrument.asset_id)
    ) then
      raise exception 'Trading is not available for this account and market. Check account eligibility and market capability.' using errcode='P0001';
    end if;
  end if;
  perform private.assert_temporary_ngn_market_scope(instrument.id,auth.uid(),instrument.asset_id,false);
  if p_amount is null or p_amount<instrument.min_order_notional then raise exception 'Stake is below the market minimum' using errcode='22023'; end if;
  select * into outcome from market.outcomes where instrument_id=instrument.id and code=upper(trim(p_outcome_code));
  if outcome.id is null then raise exception 'Outcome not found' using errcode='P0002'; end if;

  select coalesce(sum(amount),0),coalesce(sum(amount) filter(where outcome_id=outcome.id),0)
  into total_pool,outcome_pool
  from trading.pool_stakes where instrument_id=instrument.id;

  select q.fee_amount,q.policy_version_id into fee,fee_pv from command.quote_trading_fee(p_amount,'TAKER') q;
  if outcome_pool+p_amount>0 then
    est_gross:=round((p_amount/(outcome_pool+p_amount))*(total_pool+p_amount),18);
  end if;
  select q.fee_amount,q.policy_version_id into est_settlement_fee,est_pv from command.quote_settlement_fee(est_gross) q;

  return jsonb_build_object(
    'instrumentPublicId',instrument.public_id,
    'instrumentId',instrument.id,
    'outcomeId',outcome.id,
    'outcomeCode',outcome.code,
    'assetId',instrument.asset_id,
    'amount',p_amount,
    'tradingFee',coalesce(fee,0),
    'tradingFeePolicyVersionId',fee_pv,
    'maximumCashDebit',p_amount+coalesce(fee,0),
    'poolTotalBefore',total_pool,
    'outcomePoolBefore',outcome_pool,
    'poolTotalAfter',total_pool+p_amount,
    'outcomePoolAfter',outcome_pool+p_amount,
    'impliedProbability',case when total_pool+p_amount>0 then round((outcome_pool+p_amount)/(total_pool+p_amount),18) else 0.5 end,
    'estimatedGrossPayout',est_gross,
    'estimatedSettlementFee',coalesce(est_settlement_fee,0),
    'estimatedNetPayout',greatest(est_gross-coalesce(est_settlement_fee,0),0),
    'quotedAt',statement_timestamp()
  );
end;
$function$
;

CREATE OR REPLACE FUNCTION public.place_pool_stake(p_instrument_public_id uuid, p_outcome_code text, p_amount numeric, p_idempotency_key text)
 RETURNS jsonb
 LANGUAGE plpgsql
 SECURITY DEFINER
 SET search_path TO ''
AS $function$
declare
  acct public.user_accounts;
  instrument market.instruments;
  outcome market.outcomes;
  existing trading.pool_stakes;
  v_public_id uuid := gen_random_uuid();
  v_available bigint;
  v_collateral bigint;
  v_fee_account bigint;
  v_balance numeric(38,18);
  v_fee numeric(38,18) := 0;
  v_fee_pv bigint;
  v_stake_journal bigint;
  v_fee_journal bigint;
  v_asset_code text;
  v_test_credit_active boolean:=false;
begin
  acct := private.require_active_account();
  if p_idempotency_key is null or char_length(p_idempotency_key) < 8 or char_length(p_idempotency_key) > 200 then
    raise exception 'A valid idempotency key is required' using errcode = '22023';
  end if;

  select * into existing
  from trading.pool_stakes
  where user_id = auth.uid() and idempotency_key = p_idempotency_key;
  if existing.id is not null then
    if exists (
      select 1
      from market.instruments i
      join public.assets a on a.id = i.asset_id
      where i.id = existing.instrument_id and a.code = 'NGN'
    ) and not coalesce((select gate.allowed from public.can_access_ngn_services() gate limit 1), false) then
      raise exception 'NGN service requires current location verification' using errcode = '42501';
    end if;
    return jsonb_build_object('stakeId', existing.public_id, 'amount', existing.amount, 'tradingFee', existing.trading_fee_amount, 'status', 'COMMITTED');
  end if;

  select * into instrument
  from market.instruments
  where public_id = p_instrument_public_id
  for share;
  if instrument.id is null then raise exception 'Market not found' using errcode = 'P0002'; end if;
  if instrument.liquidity_model <> 'POOL' then raise exception 'This market does not use pooled staking' using errcode = 'P0001'; end if;
  if instrument.status <> 'OPEN'
     or instrument.opened_at is null
     or instrument.opened_at > statement_timestamp()
     or (instrument.closed_at is not null and instrument.closed_at <= statement_timestamp()) then
    raise exception 'Market is not open' using errcode = 'P0001';
  end if;
  select a.code into v_asset_code from public.assets a where a.id=instrument.asset_id and a.status='ACTIVE';
  select exists(
    select 1 from public.temporary_ngn_test_credit_grants g
    where g.user_id=auth.uid() and g.asset_id=instrument.asset_id and g.status='ACTIVE'
  ) into v_test_credit_active;
  if v_asset_code='NGN' and not coalesce((select gate.allowed from public.can_access_ngn_services() gate limit 1),false) then
    raise exception 'NGN service requires current location verification. Verify your current location and try again.' using errcode='42501';
  end if;
  if not private.trade_access_satisfies(auth.uid(), acct.country_code, instrument.asset_id) then
    if not (
      v_asset_code='NGN'
      and v_test_credit_active
      and private.service_available('trading',auth.uid())
      and private.asset_available_in_country(acct.country_code,instrument.asset_id)
    ) then
      raise exception 'Trading is not available for this account and market. Check account eligibility and market capability.' using errcode='P0001';
    end if;
  end if;
  if p_amount is null or p_amount < instrument.min_order_notional then
    raise exception 'Stake is below the market minimum' using errcode = '22023';
  end if;

  select * into outcome
  from market.outcomes
  where instrument_id = instrument.id and code = upper(trim(p_outcome_code));
  if outcome.id is null then raise exception 'Outcome not found' using errcode = 'P0002'; end if;

  select q.fee_amount, q.policy_version_id into v_fee, v_fee_pv
  from command.quote_trading_fee(p_amount, 'TAKER') q;
  v_fee := coalesce(v_fee, 0);
  v_available := finance.ensure_user_account(auth.uid(), instrument.asset_id, 'USER_AVAILABLE');
  v_collateral := finance.ensure_market_collateral_account(instrument.id, instrument.asset_id);
  perform pg_advisory_xact_lock(hashtextextended('vad-wallet:' || auth.uid()::text || ':' || instrument.asset_id::text, 0));
  perform pg_advisory_xact_lock(hashtextextended('vad-pool:' || instrument.id::text, 0));
  perform private.assert_temporary_ngn_market_scope(instrument.id,auth.uid(),instrument.asset_id,true);
  v_balance := finance.account_balance(v_available);
  if v_balance < p_amount + v_fee then
    raise exception 'Insufficient available balance including trading fee' using errcode = 'P0001';
  end if;

  v_stake_journal := finance.transfer(
    instrument.asset_id, v_available, v_collateral, p_amount,
    'POOL_STAKE', 'pool-stake:' || v_public_id::text, 'POOL_STAKE', v_public_id::text,
    'Commit peer-funded VAD market stake', auth.uid()
  );
  if v_fee > 0 then
    v_fee_account := finance.ensure_platform_account(instrument.asset_id, 'PLATFORM_TRADING_FEE_REVENUE');
    v_fee_journal := finance.transfer(
      instrument.asset_id, v_available, v_fee_account, v_fee,
      'TRADING_FEE', 'pool-stake-fee:' || v_public_id::text, 'POOL_STAKE', v_public_id::text,
      'VAD pooled-stake execution fee', auth.uid()
    );
  end if;

  insert into trading.pool_stakes(
    public_id, user_id, instrument_id, outcome_id, amount, trading_fee_amount,
    fee_policy_version_id, stake_journal_id, fee_journal_id, idempotency_key
  ) values(
    v_public_id, auth.uid(), instrument.id, outcome.id, p_amount, v_fee,
    v_fee_pv, v_stake_journal, v_fee_journal, p_idempotency_key
  ) returning * into existing;

  insert into eventing.domain_events(event_type, aggregate_type, aggregate_id, payload, idempotency_key)
  values(
    'POOL_STAKE_PLACED', 'POOL_STAKE', v_public_id::text,
    jsonb_build_object('stake_id', v_public_id, 'instrument_id', instrument.public_id, 'user_id', auth.uid(), 'outcome', outcome.code, 'amount', p_amount, 'fee', v_fee),
    'pool-stake-placed:' || v_public_id::text
  ) on conflict(idempotency_key) do nothing;

  perform command.refresh_market_catalog(instrument.id);
  return jsonb_build_object('stakeId', v_public_id, 'marketId', instrument.public_id, 'outcomeCode', outcome.code, 'amount', p_amount, 'tradingFee', v_fee, 'status', 'COMMITTED');
end;
$function$
;

CREATE OR REPLACE FUNCTION public.transfer_asset_to_email(p_recipient_email text, p_asset_code text, p_amount numeric, p_idempotency_key uuid)
 RETURNS jsonb
 LANGUAGE plpgsql
 SECURITY DEFINER
 SET search_path TO ''
AS $function$
declare
  v_sender_id uuid:=auth.uid();
  v_recipient_id uuid;
  v_sender_country text;
  v_recipient_country text;
  v_sender_status text;
  v_recipient_status text;
  v_asset_code text:=upper(trim(coalesce(p_asset_code,'')));
  v_asset_id bigint;
  v_minor_units integer;
  v_amount numeric;
  v_sender_eligible text[];
  v_sender_policy record;
  v_source_account_id bigint;
  v_recipient_account_id bigint;
  v_source_status text;
  v_recipient_account_status text;
  v_available numeric(38,18);
  v_transfer public.asset_transfers%rowtype;
  v_transfer_public_id uuid;
  v_journal_id bigint;
  v_journal_public_id uuid;
  v_idempotency text;
  v_email text:=lower(trim(coalesce(p_recipient_email,'')));
  v_sender_test_grant public.temporary_ngn_test_credit_grants%rowtype;
  v_recipient_test_grant public.temporary_ngn_test_credit_grants%rowtype;
  v_recipient_test_grant_created boolean:=false;
  v_available_id_check bigint;
  v_reserved_id_check bigint;
  v_pending_id_check bigint;
begin
  if v_sender_id is null then
    raise exception 'Sign in before sending assets.' using errcode='28000';
  end if;
  if p_idempotency_key is null then
    raise exception 'A transfer request key is required. Please retry.' using errcode='22023';
  end if;
  if v_email='' or length(v_email)>254 or position('@' in v_email)<2 or v_email ~ '[[:space:]]' then
    raise exception 'Enter a valid recipient email address.' using errcode='22023';
  end if;
  if v_asset_code not in ('NGN','USDC') then
    raise exception 'Only real NGN and VAD ledger USDC transfers are supported. TNGN has been decommissioned.' using errcode='22023';
  end if;
  if p_amount is null or p_amount<=0 or p_amount>999999999999999999 then
    raise exception 'Enter an amount greater than zero.' using errcode='22023';
  end if;

  select u.id into v_recipient_id
  from auth.users u
  where lower(u.email)=v_email
  limit 1;
  if v_recipient_id is null then
    raise exception 'No VAD account exists for that email address. No funds were moved.' using errcode='P0002';
  end if;
  if v_recipient_id=v_sender_id then
    raise exception 'Choose another VAD account. You cannot transfer assets to yourself.' using errcode='22023';
  end if;

  select ua.status,case when upper(trim(coalesce(ua.country_code,''))) in ('NG','NGA','NIGERIA') then 'NG' else upper(trim(coalesce(ua.country_code,''))) end
    into v_sender_status,v_sender_country
  from public.user_accounts ua where ua.user_id=v_sender_id;
  if v_sender_status is distinct from 'ACTIVE' then
    raise exception 'Your VAD account is not active for transfers.' using errcode='42501';
  end if;
  select ua.status,case when upper(trim(coalesce(ua.country_code,''))) in ('NG','NGA','NIGERIA') then 'NG' else upper(trim(coalesce(ua.country_code,''))) end
    into v_recipient_status,v_recipient_country
  from public.user_accounts ua where ua.user_id=v_recipient_id;
  if v_recipient_status is distinct from 'ACTIVE' then
    raise exception 'The recipient account is registered but is not active for transfers.' using errcode='42501';
  end if;

  select a.id,a.minor_units into v_asset_id,v_minor_units
  from public.assets a
  where a.code=v_asset_code and a.status='ACTIVE';
  if v_asset_id is null then
    raise exception 'The selected asset is not currently available for transfers.' using errcode='42501';
  end if;
  if p_amount<>round(p_amount,v_minor_units) then
    raise exception 'The amount has too many decimal places for %.',v_asset_code using errcode='22023';
  end if;
  v_amount:=p_amount;

  select * into v_sender_policy from public.get_my_currency_policy() limit 1;
  v_sender_eligible:=coalesce(v_sender_policy.eligible_asset_codes,array[]::text[]);
  if not (v_asset_code=any(v_sender_eligible)) then
    raise exception 'Your account is not eligible to hold %.',v_asset_code using errcode='42501';
  end if;

  -- USD Coin is available to supported VAD accounts. NGN transfers require
  -- both accounts to be Nigerian and NGN to be enabled for that jurisdiction.
  if v_asset_code='NGN' then
    if not coalesce((select gate.allowed from public.can_access_ngn_services() gate limit 1),false) then
      raise exception 'NGN transfers require current location verification in Nigeria.' using errcode='42501';
    end if;
    if v_sender_country<>'NG' or v_recipient_country<>'NG' then
      raise exception 'NGN transfers are only available between eligible Nigerian VAD accounts.' using errcode='42501';
    end if;
    if not exists (
      select 1
      from public.assets a
      join public.jurisdiction_assets ja on ja.asset_id=a.id and ja.status='ACTIVE'
      join public.jurisdictions j on j.id=ja.jurisdiction_id and j.status='ACTIVE'
      where a.id=v_asset_id
        and upper(trim(j.country_code)) in ('NG','NGA','NIGERIA')
    ) then
      raise exception 'NGN transfers are disabled by jurisdiction policy.' using errcode='42501';
    end if;
  end if;

  -- Serialize retries for the same sender/request key before checking for
  -- an existing transfer, preventing concurrent network retries from double-debiting.
  perform pg_advisory_xact_lock(hashtextextended(
    'asset-transfer-request:'||v_sender_id::text||':'||p_idempotency_key::text,0
  ));

  -- Existing request-key reuse is accepted only for the same immutable transfer.
  select * into v_transfer
  from public.asset_transfers t
  where t.sender_user_id=v_sender_id and t.idempotency_key=p_idempotency_key
  for update;
  if found then
    if v_transfer.recipient_user_id<>v_recipient_id
       or v_transfer.asset_id<>v_asset_id
       or v_transfer.amount<>v_amount then
      raise exception 'This request key was already used for a different transfer. Start a new transfer.' using errcode='22023';
    end if;
    if v_transfer.status='POSTED' and v_transfer.journal_id is not null then
      select j.public_id into v_journal_public_id from finance.ledger_journals j where j.id=v_transfer.journal_id;
      return jsonb_build_object(
        'transferId',v_transfer.public_id,
        'journalId',v_journal_public_id,
        'assetCode',v_asset_code,
        'amount',v_amount,
        'status','POSTED',
        'idempotentReplay',true,
        'temporaryTestCredit',exists(
          select 1 from public.temporary_ngn_test_credit_transfers tt where tt.transfer_public_id=v_transfer.public_id
        )
      );
    end if;
    raise exception 'This transfer request is already being processed. Retry shortly using the same request.' using errcode='40001';
  end if;

  -- Serialize transfers involving these two user/asset accounts, then lock both
  -- ledger accounts so two simultaneous sends cannot spend the same available balance.
  perform pg_advisory_xact_lock(hashtextextended(
    'asset-transfer:'||least(v_sender_id::text,v_recipient_id::text)||':'||greatest(v_sender_id::text,v_recipient_id::text)||':'||v_asset_id::text,0
  ));

  if v_asset_code='NGN' then
    select * into v_sender_test_grant
    from public.temporary_ngn_test_credit_grants g
    where g.user_id=v_sender_id and g.asset_id=v_asset_id and g.status='ACTIVE'
    order by g.created_at desc limit 1 for update;

    select * into v_recipient_test_grant
    from public.temporary_ngn_test_credit_grants g
    where g.user_id=v_recipient_id and g.asset_id=v_asset_id and g.status='ACTIVE'
    order by g.created_at desc limit 1 for update;

    if v_sender_test_grant.id is null and v_recipient_test_grant.id is not null then
      raise exception 'Real NGN cannot be transferred into a temporary test-credit account. No funds were moved.' using errcode='42501';
    end if;

    if v_sender_test_grant.id is not null and v_recipient_test_grant.id is null then
      if exists (
        select 1 from public.temporary_ngn_test_credit_grants g
        where g.user_id=v_recipient_id and g.asset_id=v_asset_id and g.status='REVOKED'
      ) then
        raise exception 'The recipient''s previous temporary test credit was revoked. A super administrator must authorize a new test grant.' using errcode='42501';
      end if;

      if exists (
        select 1 from public.user_currency_preferences cp
        where cp.user_id=v_recipient_id and not ('NGN'=any(cp.enabled_asset_codes))
      ) then
        raise exception 'The recipient must enable NGN in Currency settings before receiving temporary test funds.' using errcode='42501';
      end if;

      if exists (
        select 1 from finance.ledger_accounts la
        where la.asset_id=v_asset_id and la.owner_type='USER'
          and la.owner_reference=v_recipient_id::text
          and la.account_type in ('USER_AVAILABLE','USER_RESERVED','WITHDRAWAL_PENDING')
          and finance.account_balance(la.id)<>0
      ) then
        raise exception 'The recipient has an existing real NGN balance. Test funds cannot be mixed with cash-funded NGN.' using errcode='55000';
      end if;

      if exists (
        select 1 from payments.intents pi
        where pi.user_id=v_recipient_id and pi.asset_id=v_asset_id
          and pi.operation in ('DEPOSIT','WITHDRAWAL')
          and pi.status not in ('SETTLED','FAILED','CANCELLED','EXPIRED','SUCCEEDED','REJECTED')
      ) then
        raise exception 'Resolve the recipient''s pending NGN deposit or withdrawal before sending test funds.' using errcode='55000';
      end if;

      if exists (
        select 1 from trading.orders o join market.instruments i on i.id=o.instrument_id
        where o.user_id=v_recipient_id and i.asset_id=v_asset_id and o.status in ('OPEN','PARTIALLY_FILLED')
      ) or exists (
        select 1 from trading.pool_stakes s join market.instruments i on i.id=s.instrument_id
        where s.user_id=v_recipient_id and i.asset_id=v_asset_id and i.status='OPEN'
      ) or exists (
        select 1 from trading.positions pos join market.instruments i on i.id=pos.instrument_id
        where pos.user_id=v_recipient_id and i.asset_id=v_asset_id and i.status='OPEN' and pos.quantity<>0
      ) then
        raise exception 'The recipient has an open NGN order, stake or position. Resolve it before receiving temporary test funds.' using errcode='55000';
      end if;

      insert into public.temporary_ngn_test_credit_grants(
        user_id,asset_id,amount,status,reason,created_by
      ) values (
        v_recipient_id,v_asset_id,v_amount,'ACTIVE',
        'Temporary non-withdrawable NGN test credit received by internal email transfer from '||coalesce(v_sender_email,'a VAD account')||'. Uses the standard NGN market order and settlement pipeline.',
        v_sender_id
      ) returning * into v_recipient_test_grant;
      v_recipient_test_grant_created:=true;
    end if;
  end if;

  select la.id,la.status into v_source_account_id,v_source_status
  from finance.ledger_accounts la
  where la.asset_id=v_asset_id and la.owner_type='USER'
    and la.owner_reference=v_sender_id::text and la.account_type='USER_AVAILABLE'
  for update;
  if v_source_account_id is null then
    raise exception 'Your % wallet is not ready for transfers. Fund it through an approved NGN/USDC funding method first.',v_asset_code using errcode='P0002';
  end if;
  if v_source_status<>'ACTIVE' then
    raise exception 'Your % wallet is frozen or closed and cannot send assets.',v_asset_code using errcode='42501';
  end if;

  insert into finance.ledger_accounts(asset_id,account_type,owner_type,owner_reference,status)
  values(v_asset_id,'USER_AVAILABLE','USER',v_recipient_id::text,'ACTIVE')
  on conflict(asset_id,account_type,owner_type,owner_reference) do nothing;

  select la.id,la.status into v_recipient_account_id,v_recipient_account_status
  from finance.ledger_accounts la
  where la.asset_id=v_asset_id and la.owner_type='USER'
    and la.owner_reference=v_recipient_id::text and la.account_type='USER_AVAILABLE'
  for update;
  if v_recipient_account_id is null then
    raise exception 'The recipient % wallet could not be prepared. No funds were moved.',v_asset_code using errcode='P0002';
  end if;
  if v_recipient_account_status<>'ACTIVE' then
    raise exception 'The recipient % wallet is frozen or closed. No funds were moved.',v_asset_code using errcode='42501';
  end if;

  v_available:=finance.account_balance(v_source_account_id);
  if v_available<v_amount then
    raise exception 'Insufficient available % balance. No funds were moved.',v_asset_code using errcode='22023';
  end if;

  insert into public.asset_transfers(
    sender_user_id,recipient_user_id,asset_id,amount,idempotency_key,status
  ) values(v_sender_id,v_recipient_id,v_asset_id,v_amount,p_idempotency_key,'PROCESSING')
  returning public_id into v_transfer_public_id;

  v_idempotency:='USER_ASSET_TRANSFER:'||v_sender_id::text||':'||p_idempotency_key::text;
  v_journal_id:=finance.transfer(
    v_asset_id,
    v_source_account_id,
    v_recipient_account_id,
    v_amount,
    'USER_ASSET_TRANSFER',
    v_idempotency,
    'USER_ASSET_TRANSFER',
    v_transfer_public_id::text,
    'VAD account-to-account transfer',
    v_sender_id
  );

  select j.public_id into v_journal_public_id
  from finance.ledger_journals j where j.id=v_journal_id;

  update public.asset_transfers
  set status='POSTED',journal_id=v_journal_id
  where public_id=v_transfer_public_id;

  if v_asset_code='NGN' and v_sender_test_grant.id is not null then
    insert into public.temporary_ngn_test_credit_transfers(
      transfer_public_id,sender_grant_id,recipient_grant_id,asset_id,amount,
      recipient_grant_created,journal_id
    ) values(
      v_transfer_public_id,v_sender_test_grant.id,v_recipient_test_grant.id,v_asset_id,v_amount,
      v_recipient_test_grant_created,v_journal_id
    );
    if v_recipient_test_grant_created then
      update public.temporary_ngn_test_credit_grants
      set grant_journal_id=v_journal_id
      where id=v_recipient_test_grant.id;
      insert into audit.records(actor_user_id,actor_type,action,resource_type,resource_id,before_state,after_state,reason,request_id,occurred_at,metadata)
      values(v_sender_id,'USER','TEMPORARY_NGN_TEST_CREDIT_RECEIVED','TEMPORARY_TEST_CREDIT',v_recipient_test_grant.public_id::text,
        null,jsonb_build_object('status','ACTIVE','asset_code','NGN','amount',v_amount,'withdrawals_blocked',true,'deposits_blocked',true,'transfers_restricted_to_test_credit_accounts',true),
        'Temporary NGN test credit received by internal email transfer. No real NGN cash was created.',
        gen_random_uuid(),statement_timestamp(),
        jsonb_build_object('sender_user_id',v_sender_id,'sender_grant_id',v_sender_test_grant.public_id,
          'recipient_user_id',v_recipient_id,'transfer_id',v_transfer_public_id,'journal_id',v_journal_id,'amount',v_amount));
    end if;
  end if;

  return jsonb_build_object(
    'transferId',v_transfer_public_id,
    'journalId',v_journal_public_id,
    'assetCode',v_asset_code,
    'amount',v_amount,
    'status','POSTED',
    'idempotentReplay',false,
    'temporaryTestCredit',v_asset_code='NGN' and v_sender_test_grant.id is not null
  );
end;
$function$
;

CREATE OR REPLACE FUNCTION public.admin_revoke_temporary_ngn_test_credit(p_grant_public_id uuid, p_reason text DEFAULT 'Temporary market testing completed'::text)
 RETURNS jsonb
 LANGUAGE plpgsql
 SECURITY DEFINER
 SET search_path TO ''
AS $function$
declare
  v_grant public.temporary_ngn_test_credit_grants%rowtype;
  v_available_id bigint;
  v_reserved_id bigint;
  v_pending_id bigint;
  v_funding_id bigint;
  v_balance numeric(38,18):=0;
  v_journal_id bigint;
  v_asset_code text;
  v_expected_net numeric(38,18):=0;
begin
  if auth.uid() is null or not coalesce(private.is_super_admin(),false) then
    raise exception 'Super administrator permission is required to revoke temporary test funding.' using errcode='42501';
  end if;
  if p_grant_public_id is null then raise exception 'A test-credit grant reference is required.' using errcode='22023'; end if;

  select * into v_grant from public.temporary_ngn_test_credit_grants where public_id=p_grant_public_id for update;
  if v_grant.id is null then raise exception 'Temporary test-credit grant not found.' using errcode='P0002'; end if;
  if v_grant.status='REVOKED' then
    return jsonb_build_object('status','REVOKED','grantId',v_grant.public_id,
      'amountReturned',v_grant.amount_returned,'amountConsumed',v_grant.amount_consumed,'idempotentReplay',true);
  end if;

  select code into v_asset_code from public.assets where id=v_grant.asset_id;
  if v_asset_code<>'NGN' then raise exception 'Only NGN temporary test credits can be revoked by this operation.' using errcode='22023'; end if;
  perform pg_advisory_xact_lock(hashtextextended('temporary-ngn-test-credit:'||v_grant.user_id::text,0));

  if exists (
    select 1 from trading.orders o join market.instruments i on i.id=o.instrument_id
    where o.user_id=v_grant.user_id and o.status in ('OPEN','PARTIALLY_FILLED') and i.asset_id=v_grant.asset_id
  ) then raise exception 'Cancel or complete the user''s open NGN orders before revoking the test credit.' using errcode='55000'; end if;
  if exists (
    select 1 from trading.pool_stakes s join market.instruments i on i.id=s.instrument_id
    where s.user_id=v_grant.user_id and i.asset_id=v_grant.asset_id and i.status='OPEN'
  ) then raise exception 'Wait until all NGN market stakes have resolved before revoking the test credit.' using errcode='55000'; end if;
  if exists (
    select 1 from trading.positions pos join market.instruments i on i.id=pos.instrument_id
    where pos.user_id=v_grant.user_id and i.asset_id=v_grant.asset_id and i.status='OPEN' and pos.quantity<>0
  ) then raise exception 'Wait until all NGN positions have settled before revoking the test credit.' using errcode='55000'; end if;

  v_available_id:=finance.ensure_user_account(v_grant.user_id,v_grant.asset_id,'USER_AVAILABLE');
  v_reserved_id:=finance.ensure_user_account(v_grant.user_id,v_grant.asset_id,'USER_RESERVED');
  v_pending_id:=finance.ensure_user_account(v_grant.user_id,v_grant.asset_id,'WITHDRAWAL_PENDING');
  if finance.account_balance(v_reserved_id)<>0 or finance.account_balance(v_pending_id)<>0 then
    raise exception 'NGN reserved or pending-withdrawal funds remain; reconcile them before revoking the test credit.' using errcode='55000';
  end if;

  perform pg_advisory_xact_lock(hashtextextended('vad-wallet:'||v_grant.user_id::text||':'||v_grant.asset_id::text,0));
  v_balance:=greatest(finance.account_balance(v_available_id),0);
  select greatest(
    v_grant.amount
      + coalesce(sum(tt.amount) filter(where tt.recipient_grant_id=v_grant.id and not tt.recipient_grant_created),0)
      - coalesce(sum(tt.amount) filter(where tt.sender_grant_id=v_grant.id),0),
    0
  ) into v_expected_net
  from public.temporary_ngn_test_credit_transfers tt
  where tt.sender_grant_id=v_grant.id or tt.recipient_grant_id=v_grant.id;

  select id into v_funding_id from finance.ledger_accounts
  where asset_id=v_grant.asset_id and account_type='TREASURY' and owner_type='PLATFORM'
    and owner_reference='VAD_TEMPORARY_TEST_CREDIT' and status='ACTIVE';
  if v_funding_id is null then raise exception 'Temporary test-funding ledger account is missing.' using errcode='23514'; end if;

  if v_balance>0 then
    v_journal_id:=finance.transfer(v_grant.asset_id,v_available_id,v_funding_id,v_balance,
      'TEMPORARY_TEST_CREDIT_REVERSAL','temporary-test-credit-reversal:'||v_grant.public_id::text,
      'TEMPORARY_TEST_CREDIT',v_grant.public_id::text,
      'Reverse remaining non-withdrawable temporary NGN market-test credit and test-trading proceeds.',auth.uid());
  end if;
  update public.temporary_ngn_test_credit_grants
  set status='REVOKED',revoke_journal_id=v_journal_id,amount_returned=v_balance,
      amount_consumed=greatest(v_expected_net-least(v_expected_net,v_balance),0),
      amount_overage_returned=greatest(v_balance-v_expected_net,0),
      revoked_by=auth.uid(),revoked_at=statement_timestamp(),
      revoke_reason=coalesce(nullif(trim(p_reason),''),'Temporary market testing completed')
  where id=v_grant.id;

  insert into audit.records(actor_user_id,actor_type,action,resource_type,resource_id,before_state,after_state,reason,request_id,occurred_at,metadata)
  values(auth.uid(),'ADMIN','TEMPORARY_NGN_TEST_CREDIT_REVOKED','TEMPORARY_TEST_CREDIT',v_grant.public_id::text,
    jsonb_build_object('status','ACTIVE','amount',v_grant.amount),
    jsonb_build_object('status','REVOKED','amountReturned',v_balance,
      'amountConsumed',greatest(v_expected_net-least(v_expected_net,v_balance),0)),
    coalesce(nullif(trim(p_reason),''),'Temporary market testing completed'),
    gen_random_uuid(),statement_timestamp(),
    jsonb_build_object('user_id',v_grant.user_id,'asset_code','NGN','reversal_journal_id',v_journal_id));

  return jsonb_build_object('status','REVOKED','grantId',v_grant.public_id,
    'amountReturned',v_balance,'amountConsumed',greatest(v_expected_net-least(v_expected_net,v_balance),0),
    'overageReturned',greatest(v_balance-v_expected_net,0),'idempotentReplay',false);
end;
$function$
;

create or replace function public.my_temporary_ngn_test_credit_status()
returns jsonb
language plpgsql
stable
security definer
set search_path=''
as $function$
declare
  v_grant public.temporary_ngn_test_credit_grants%rowtype;
  v_asset_id bigint;
  v_available_id bigint;
  v_balance numeric(38,18):=0;
begin
  if auth.uid() is null then raise exception 'Authentication required' using errcode='28000'; end if;
  select id into v_asset_id from public.assets where code='NGN';
  if v_asset_id is null then return jsonb_build_object('active',false,'assetCode','NGN'); end if;

  select * into v_grant
  from public.temporary_ngn_test_credit_grants
  where user_id=auth.uid() and asset_id=v_asset_id and status='ACTIVE'
  order by created_at desc limit 1;

  if v_grant.id is null then return jsonb_build_object('active',false,'assetCode','NGN'); end if;

  select id into v_available_id
  from finance.ledger_accounts
  where asset_id=v_asset_id and owner_type='USER'
    and owner_reference=auth.uid()::text and account_type='USER_AVAILABLE' and status='ACTIVE';
  if v_available_id is not null then v_balance:=finance.account_balance(v_available_id); end if;

  return jsonb_build_object(
    'active',true,'publicId',v_grant.public_id,'assetCode','NGN',
    'amount',v_grant.amount,'availableBalance',greatest(v_balance,0),
    'createdAt',v_grant.created_at,'withdrawalsBlocked',true,
    'transfersBlocked',false,'transfersRestricted',true,'depositsBlocked',true,
    'marketOrdersUseStandardSettlement',true,
    'message','Temporary non-cash NGN test credit uses real NGN market instruments and standard settlement. Email transfers are restricted to existing eligible Nigerian VAD accounts with test-credit lineage; deposits and withdrawals remain blocked.'
  );
end;
$function$;

revoke all on function public.my_temporary_ngn_test_credit_status() from public,anon;
grant execute on function public.my_temporary_ngn_test_credit_status() to authenticated;

select pg_notify('pgrst','reload schema');
commit;
