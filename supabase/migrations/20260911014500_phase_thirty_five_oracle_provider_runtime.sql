create or replace function public.internal_oracle_due_events(
  p_event_public_id uuid default null,
  p_limit integer default 20
)
returns jsonb
language plpgsql
stable
security definer
set search_path=''
as $$
declare result jsonb;
begin
  if auth.role()<>'service_role' then raise exception 'Service role required' using errcode='42501'; end if;
  with due as (
    select e.id,e.public_id,e.title,e.category,e.status,e.normalized_parameters,e.resolution_scope,
           e.closes_at,e.resolves_after,
           op.id oracle_policy_id,op.public_id oracle_policy_public_id,op.source_hierarchy,op.consensus_rule,
           oc.code capability_code
    from market.canonical_events e
    join oracle.event_policy_bindings b on b.event_id=e.id
    join oracle.policies op on op.id=b.oracle_policy_id and op.status='ACTIVE'
    join oracle.capabilities oc on oc.id=op.capability_id
    where e.status in ('AWAITING_ORACLE','PROVISIONALLY_RESOLVED')
      and coalesce(e.resolves_after,e.closes_at)<=statement_timestamp()
      and (p_event_public_id is null or e.public_id=p_event_public_id)
      and not exists(
        select 1 from oracle.disputes d
        where d.event_id=e.id and d.status in ('OPEN','UNDER_REVIEW','ESCALATED')
      )
    order by coalesce(e.resolves_after,e.closes_at),e.id
    limit greatest(1,least(coalesce(p_limit,20),100))
  )
  select coalesce(jsonb_agg(jsonb_build_object(
    'eventId',d.id,
    'eventPublicId',d.public_id,
    'title',d.title,
    'category',d.category,
    'status',d.status,
    'normalizedParameters',d.normalized_parameters,
    'resolutionScope',d.resolution_scope,
    'closesAt',d.closes_at,
    'resolvesAfter',d.resolves_after,
    'oraclePolicyId',d.oracle_policy_id,
    'oraclePolicyPublicId',d.oracle_policy_public_id,
    'capabilityCode',d.capability_code,
    'sourceHierarchy',d.source_hierarchy,
    'consensusRule',d.consensus_rule,
    'outcomes',coalesce((
      select jsonb_agg(jsonb_build_object('code',o.code,'label',o.label) order by i.id,o.display_order)
      from market.instruments i
      join market.outcomes o on o.instrument_id=i.id
      where i.canonical_event_id=d.id
    ),'[]'::jsonb)
  ) order by coalesce(d.resolves_after,d.closes_at),d.id),'[]'::jsonb) into result
  from due d;
  return result;
end;
$$;
revoke all on function public.internal_oracle_due_events(uuid,integer) from public,anon,authenticated;
grant execute on function public.internal_oracle_due_events(uuid,integer) to service_role;

create or replace function public.internal_record_oracle_provider_health(
  p_provider_code text,
  p_environment text,
  p_health_status text,
  p_configured boolean,
  p_latency_ms integer default null,
  p_metadata jsonb default '{}'::jsonb
)
returns void
language plpgsql
security definer
set search_path=''
as $$
declare provider_id bigint; health_status text:=upper(trim(p_health_status));
begin
  if auth.role()<>'service_role' then raise exception 'Service role required' using errcode='42501'; end if;
  if health_status not in ('HEALTHY','DEGRADED','UNAVAILABLE','UNKNOWN') then
    raise exception 'Invalid provider health status' using errcode='22023';
  end if;
  if jsonb_typeof(coalesce(p_metadata,'{}'::jsonb))<>'object' then
    raise exception 'Provider health metadata must be an object' using errcode='22023';
  end if;
  select id into provider_id from integration.providers
  where code=upper(trim(p_provider_code)) and environment=upper(trim(p_environment)) and provider_type='ORACLE';
  if provider_id is null then raise exception 'Oracle provider not found' using errcode='P0002'; end if;
  update integration.providers
     set public_metadata=jsonb_set(coalesce(public_metadata,'{}'::jsonb),'{configured}',to_jsonb(coalesce(p_configured,false)),true),
         updated_at=statement_timestamp()
   where id=provider_id;
  insert into integration.provider_health(provider_id,status,latency_ms,success_rate,error_rate,last_success_at,last_failure_at,checked_at,metadata)
  values(
    provider_id,health_status,p_latency_ms,
    case when health_status='HEALTHY' then 1 else 0 end,
    case when health_status='HEALTHY' then 0 else 1 end,
    case when health_status='HEALTHY' then statement_timestamp() else null end,
    case when health_status in ('DEGRADED','UNAVAILABLE') then statement_timestamp() else null end,
    statement_timestamp(),coalesce(p_metadata,'{}'::jsonb)
  )
  on conflict(provider_id) do update set
    status=excluded.status,
    latency_ms=excluded.latency_ms,
    success_rate=excluded.success_rate,
    error_rate=excluded.error_rate,
    last_success_at=case when excluded.status='HEALTHY' then excluded.checked_at else integration.provider_health.last_success_at end,
    last_failure_at=case when excluded.status in ('DEGRADED','UNAVAILABLE') then excluded.checked_at else integration.provider_health.last_failure_at end,
    checked_at=excluded.checked_at,
    metadata=excluded.metadata;
end;
$$;
revoke all on function public.internal_record_oracle_provider_health(text,text,text,boolean,integer,jsonb) from public,anon,authenticated;
grant execute on function public.internal_record_oracle_provider_health(text,text,text,boolean,integer,jsonb) to service_role;

