-- Observation integrity hardening: a provider is one independent vote. The caller
-- cannot manufacture multiple source_code values for the same provider.
create or replace function oracle.record_verified_observation(
  p_event_id bigint,
  p_provider_id bigint,
  p_source_code text,
  p_observed_outcome text,
  p_payload jsonb,
  p_evidence_reference text,
  p_observed_at timestamptz,
  p_idempotency_key text
)
returns bigint
language plpgsql
security definer
set search_path=''
as $$
declare
  provider integration.providers;
  ev market.canonical_events;
  observation_id bigint;
begin
  if auth.role()<>'service_role' then raise exception 'Service role required' using errcode='42501'; end if;
  if p_idempotency_key is null or char_length(p_idempotency_key)<8 then
    raise exception 'Valid observation idempotency key required' using errcode='22023';
  end if;
  if jsonb_typeof(coalesce(p_payload,'{}'::jsonb))<>'object' then
    raise exception 'Observation payload must be an object' using errcode='22023';
  end if;
  select * into provider from integration.providers where id=p_provider_id;
  if provider.id is null or provider.provider_type<>'ORACLE' or provider.status not in ('ACTIVE','DEGRADED') then
    raise exception 'Eligible oracle provider required' using errcode='23514';
  end if;
  if upper(trim(coalesce(p_source_code,'')))<>provider.code then
    raise exception 'Oracle source code must match provider identity' using errcode='23514';
  end if;
  select * into ev from market.canonical_events where id=p_event_id;
  if ev.id is null then raise exception 'Event not found' using errcode='P0002'; end if;
  if ev.status not in ('AWAITING_ORACLE','PROVISIONALLY_RESOLVED','DISPUTED') then
    raise exception 'Event is not accepting oracle observations' using errcode='P0001';
  end if;
  if not exists(
    select 1 from market.instruments i
    join market.outcomes o on o.instrument_id=i.id
    where i.canonical_event_id=ev.id and o.code=upper(trim(p_observed_outcome))
  ) then
    raise exception 'Observed outcome is invalid for event' using errcode='22023';
  end if;
  if coalesce(p_observed_at,statement_timestamp())>statement_timestamp()+interval '5 minutes' then
    raise exception 'Observation timestamp is unreasonably in the future' using errcode='22023';
  end if;
  insert into oracle.observations(
    event_id,provider_id,source_code,observed_outcome,observation_payload,evidence_reference,observed_at,verification_status,idempotency_key
  ) values(
    ev.id,provider.id,provider.code,upper(trim(p_observed_outcome)),coalesce(p_payload,'{}'::jsonb),p_evidence_reference,
    coalesce(p_observed_at,statement_timestamp()),'VERIFIED',p_idempotency_key
  )
  on conflict(idempotency_key) do nothing
  returning id into observation_id;
  if observation_id is null then
    select id into observation_id from oracle.observations where idempotency_key=p_idempotency_key;
  end if;
  perform oracle.evaluate_event_consensus(ev.id);
  return observation_id;
end;
$$;
