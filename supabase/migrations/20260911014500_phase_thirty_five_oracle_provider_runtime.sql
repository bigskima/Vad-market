-- VAD Phase 35: provider-neutral oracle runtime foundation.
-- External API calls and secrets stay in Edge Functions. PostgreSQL remains the
-- authority for provider governance, observation integrity, consensus and settlement state.

create table if not exists oracle.provider_resources (
  id bigint generated by default as identity primary key,
  provider_id bigint not null references integration.providers(id) on delete cascade,
  resource_type text not null check (resource_type in ('CRYPTO_PAIR','CANONICAL_EVENT','SPORTS_COMPETITION','PUBLIC_EVENT')),
  canonical_key text not null check (char_length(trim(canonical_key)) between 1 and 180),
  external_key text not null check (char_length(trim(external_key)) between 1 and 300),
  status text not null default 'ACTIVE' check (status in ('ACTIVE','DISABLED')),
  metadata jsonb not null default '{}'::jsonb check (jsonb_typeof(metadata)='object'),
  created_at timestamptz not null default statement_timestamp(),
  updated_at timestamptz not null default statement_timestamp(),
  unique(provider_id,resource_type,canonical_key)
);

create index if not exists oracle_provider_resources_lookup_idx
  on oracle.provider_resources(resource_type,canonical_key,status,provider_id);

do $$
begin
  if not exists (
    select 1 from pg_trigger
    where tgname='oracle_provider_resources_updated_at'
      and tgrelid='oracle.provider_resources'::regclass
  ) then
    create trigger oracle_provider_resources_updated_at
      before update on oracle.provider_resources
      for each row execute function private.set_updated_at();
  end if;
end $$;

alter table oracle.provider_resources enable row level security;
revoke all on oracle.provider_resources from public,anon,authenticated;
grant select,insert,update,delete on oracle.provider_resources to service_role;

create table if not exists oracle.ingestion_attempts (
  id bigint generated by default as identity primary key,
  event_id bigint references market.canonical_events(id) on delete cascade,
  provider_id bigint not null references integration.providers(id) on delete cascade,
  resolver_type text not null,
  attempt_key text not null unique,
  status text not null check (status in ('SUCCEEDED','FAILED','SKIPPED')),
  request_metadata jsonb not null default '{}'::jsonb check (jsonb_typeof(request_metadata)='object'),
  response_metadata jsonb not null default '{}'::jsonb check (jsonb_typeof(response_metadata)='object'),
  failure_code text,
  latency_ms integer check (latency_ms is null or latency_ms>=0),
  started_at timestamptz not null,
  completed_at timestamptz not null default statement_timestamp(),
  created_at timestamptz not null default statement_timestamp()
);

create index if not exists oracle_ingestion_attempts_event_created_idx
  on oracle.ingestion_attempts(event_id,created_at desc);
create index if not exists oracle_ingestion_attempts_provider_created_idx
  on oracle.ingestion_attempts(provider_id,created_at desc);

alter table oracle.ingestion_attempts enable row level security;
revoke all on oracle.ingestion_attempts from public,anon,authenticated;
grant select,insert,update on oracle.ingestion_attempts to service_role;

