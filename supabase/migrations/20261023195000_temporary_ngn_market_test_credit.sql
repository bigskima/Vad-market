begin;

-- A temporary NGN-denominated test grant funds the user's ordinary USER_AVAILABLE
-- account. Consequently the production order, pool, fee, collateral, and market
-- settlement paths remain unchanged. This is explicitly synthetic test credit,
-- not a deposit and not withdrawable/transferable while active.
create table if not exists public.temporary_ngn_test_credit_grants (
  id bigint generated by default as identity primary key,
  public_id uuid not null default gen_random_uuid() unique,
  user_id uuid not null references auth.users(id),
  asset_id bigint not null references public.assets(id),
  amount numeric(38,8) not null check (amount > 0),
  status text not null default 'ACTIVE' check (status in ('ACTIVE','REVOKED')),
  grant_journal_id bigint references finance.ledger_journals(id),
  revoke_journal_id bigint references finance.ledger_journals(id),
  amount_returned numeric(38,8) not null default 0 check (amount_returned >= 0),
  amount_consumed numeric(38,8) not null default 0 check (amount_consumed >= 0),
  amount_overage_returned numeric(38,8) not null default 0 check (amount_overage_returned >= 0),
  reason text not null,
  created_by uuid references auth.users(id),
  created_at timestamptz not null default statement_timestamp(),
  revoked_by uuid references auth.users(id),
  revoked_at timestamptz,
  revoke_reason text,
  constraint temporary_ngn_test_credit_revoke_state check ((status='REVOKED')=(revoked_at is not null))
);

create unique index if not exists one_active_temporary_ngn_test_credit_per_user_asset
  on public.temporary_ngn_test_credit_grants(user_id,asset_id)
  where status='ACTIVE';

alter table public.temporary_ngn_test_credit_grants enable row level security;
revoke all on public.temporary_ngn_test_credit_grants from public,anon,authenticated;
grant select,insert,update,delete on public.temporary_ngn_test_credit_grants to service_role;

create or replace function public.my_temporary_ngn_test_credit_status()
returns jsonb
language plpgsql
stable
security definer
set search_path=''
as $function$
declare
  v_grant public.temporary_ngn_test_credit_grants%rowtype;
  v_asset_id bigint;
  v_available_id bigint;
  v_balance numeric(38,18):=0;
begin
  if auth.uid() is null then
    raise exception 'Authentication required' using errcode='28000';
  end if;
  select id into v_asset_id from public.assets where code='NGN';
  if v_asset_id is null then return jsonb_build_object('active',false,'assetCode','NGN'); end if;

  select * into v_grant
  from public.temporary_ngn_test_credit_grants
  where user_id=auth.uid() and asset_id=v_asset_id and status='ACTIVE'
  order by created_at desc limit 1;

  if v_grant.id is null then
    return jsonb_build_object('active',false,'assetCode','NGN');
  end if;

  select id into v_available_id
  from finance.ledger_accounts
  where asset_id=v_asset_id and owner_type='USER'
    and owner_reference=auth.uid()::text and account_type='USER_AVAILABLE'
    and status='ACTIVE';
  if v_available_id is not null then v_balance:=finance.account_balance(v_available_id); end if;

  return jsonb_build_object(
    'active',true,'publicId',v_grant.public_id,'assetCode','NGN',
    'amount',v_grant.amount,'availableBalance',greatest(v_balance,0),
    'createdAt',v_grant.created_at,'withdrawalsBlocked',true,'transfersBlocked',true,
    'depositsBlocked',true,'marketOrdersUseStandardSettlement',true,
    'message','Temporary test credit: tradable on actual NGN markets using the normal market settlement pipeline, but not withdrawable or transferable.'
  );
end;
$function$;
revoke all on function public.my_temporary_ngn_test_credit_status() from public,anon;
grant execute on function public.my_temporary_ngn_test_credit_status() to authenticated;

create or replace function public.admin_revoke_temporary_ngn_test_credit(
  p_grant_public_id uuid,
  p_reason text default 'Temporary market testing completed'
)
returns jsonb
language plpgsql
security definer
set search_path=''
as $function$
declare
  v_grant public.temporary_ngn_test_credit_grants%rowtype;
  v_available_id bigint;
  v_reserved_id bigint;
  v_pending_id bigint;
  v_funding_id bigint;
  v_balance numeric(38,18):=0;
  v_journal_id bigint;
  v_asset_code text;
begin
  if auth.uid() is null or not coalesce(private.is_super_admin(),false) then
    raise exception 'Super administrator permission is required to revoke temporary test funding.' using errcode='42501';
  end if;
  if p_grant_public_id is null then raise exception 'A test-credit grant reference is required.' using errcode='22023'; end if;

  select * into v_grant from public.temporary_ngn_test_credit_grants where public_id=p_grant_public_id for update;
  if v_grant.id is null then raise exception 'Temporary test-credit grant not found.' using errcode='P0002'; end if;
  if v_grant.status='REVOKED' then
    return jsonb_build_object('status','REVOKED','grantId',v_grant.public_id,
      'amountReturned',v_grant.amount_returned,'amountConsumed',v_grant.amount_consumed,'idempotentReplay',true);
  end if;

  select code into v_asset_code from public.assets where id=v_grant.asset_id;
  if v_asset_code<>'NGN' then raise exception 'Only NGN temporary test credits can be revoked by this operation.' using errcode='22023'; end if;
  perform pg_advisory_xact_lock(hashtextextended('temporary-ngn-test-credit:'||v_grant.user_id::text,0));

  if exists (
    select 1 from trading.orders o join market.instruments i on i.id=o.instrument_id
    where o.user_id=v_grant.user_id and o.status in ('OPEN','PARTIALLY_FILLED') and i.asset_id=v_grant.asset_id
  ) then raise exception 'Cancel or complete the user's open NGN orders before revoking the test credit.' using errcode='55000'; end if;
  if exists (
    select 1 from trading.pool_stakes s join market.instruments i on i.id=s.instrument_id
    where s.user_id=v_grant.user_id and i.asset_id=v_grant.asset_id and i.status='OPEN'
  ) then raise exception 'Wait until all NGN market stakes have resolved before revoking the test credit.' using errcode='55000'; end if;
  if exists (
    select 1 from trading.positions pos join market.instruments i on i.id=pos.instrument_id
    where pos.user_id=v_grant.user_id and i.asset_id=v_grant.asset_id and i.status='OPEN' and pos.quantity<>0
  ) then raise exception 'Wait until all NGN positions have settled before revoking the test credit.' using errcode='55000'; end if;

  v_available_id:=finance.ensure_user_account(v_grant.user_id,v_grant.asset_id,'USER_AVAILABLE');
  v_reserved_id:=finance.ensure_user_account(v_grant.user_id,v_grant.asset_id,'USER_RESERVED');
  v_pending_id:=finance.ensure_user_account(v_grant.user_id,v_grant.asset_id,'WITHDRAWAL_PENDING');
  if finance.account_balance(v_reserved_id)<>0 or finance.account_balance(v_pending_id)<>0 then
    raise exception 'NGN reserved or pending-withdrawal funds remain; reconcile them before revoking the test credit.' using errcode='55000';
  end if;

  perform pg_advisory_xact_lock(hashtextextended('vad-wallet:'||v_grant.user_id::text||':'||v_grant.asset_id::text,0));
  v_balance:=greatest(finance.account_balance(v_available_id),0);
  select id into v_funding_id from finance.ledger_accounts
  where asset_id=v_grant.asset_id and account_type='TREASURY' and owner_type='PLATFORM'
    and owner_reference='VAD_TEMPORARY_TEST_CREDIT' and status='ACTIVE';
  if v_funding_id is null then raise exception 'Temporary test-funding ledger account is missing.' using errcode='23514'; end if;

  if v_balance>0 then
    v_journal_id:=finance.transfer(v_grant.asset_id,v_available_id,v_funding_id,v_balance,
      'TEMPORARY_TEST_CREDIT_REVERSAL','temporary-test-credit-reversal:'||v_grant.public_id::text,
      'TEMPORARY_TEST_CREDIT',v_grant.public_id::text,
      'Reverse remaining non-withdrawable temporary NGN market-test credit and test-trading proceeds.',auth.uid());
  end if;
  update public.temporary_ngn_test_credit_grants
  set status='REVOKED',revoke_journal_id=v_journal_id,amount_returned=v_balance,
      amount_consumed=greatest(amount-least(amount,v_balance),0),
      amount_overage_returned=greatest(v_balance-amount,0),
      revoked_by=auth.uid(),revoked_at=statement_timestamp(),
      revoke_reason=coalesce(nullif(trim(p_reason),''),'Temporary market testing completed')
  where id=v_grant.id;

  insert into audit.records(actor_user_id,actor_type,action,resource_type,resource_id,before_state,after_state,reason,request_id,occurred_at,metadata)
  values(auth.uid(),'ADMIN','TEMPORARY_NGN_TEST_CREDIT_REVOKED','TEMPORARY_TEST_CREDIT',v_grant.public_id::text,
    jsonb_build_object('status','ACTIVE','amount',v_grant.amount),
    jsonb_build_object('status','REVOKED','amountReturned',v_balance,
      'amountConsumed',greatest(v_grant.amount-least(v_grant.amount,v_balance),0)),
    coalesce(nullif(trim(p_reason),''),'Temporary market testing completed'),
    gen_random_uuid(),statement_timestamp(),
    jsonb_build_object('user_id',v_grant.user_id,'asset_code','NGN','reversal_journal_id',v_journal_id));

  return jsonb_build_object('status','REVOKED','grantId',v_grant.public_id,
    'amountReturned',v_balance,'amountConsumed',greatest(v_grant.amount-least(v_grant.amount,v_balance),0),
    'overageReturned',greatest(v_balance-v_grant.amount,0),'idempotentReplay',false);
end;
$function$;
revoke all on function public.admin_revoke_temporary_ngn_test_credit(uuid,text) from public,anon;
grant execute on function public.admin_revoke_temporary_ngn_test_credit(uuid,text) to authenticated;

create or replace function public.create_payment_intent(
  p_operation text,
  p_asset_code text,
  p_amount numeric,
  p_idempotency_key text
)
returns uuid
language plpgsql
security definer
set search_path=''
as $function$
declare
  quote jsonb;
  acct public.user_accounts;
  asset public.assets;
  provider bigint;
  intent payments.intents;
  available_account bigint;
  pending_account bigint;
begin
  acct := private.require_active_account();
  if p_idempotency_key is null or char_length(trim(p_idempotency_key)) < 8 then
    raise exception 'Idempotency key is required' using errcode = '22023';
  end if;

  if upper(trim(coalesce(p_asset_code,'')))='NGN'
     and upper(trim(coalesce(p_operation,''))) in ('DEPOSIT','WITHDRAWAL')
     and exists (
       select 1 from public.temporary_ngn_test_credit_grants g
       where g.user_id=auth.uid() and g.asset_id=(select a.id from public.assets a where a.code='NGN')
         and g.status='ACTIVE'
     ) then
    raise exception 'NGN deposits and withdrawals are locked while a temporary market-test credit is active. Test trades still use the normal market order and settlement path.' using errcode='42501';
  end if;

  if upper(trim(coalesce(p_asset_code, ''))) = 'NGN'
     and not coalesce((select gate.allowed from public.can_access_ngn_services() gate limit 1), false) then
    raise exception 'NGN service requires current location verification' using errcode = '42501';
  end if;

  select * into intent
  from payments.intents
  where idempotency_key = trim(p_idempotency_key);
  if intent.id is not null then
    if intent.user_id <> auth.uid() then
      raise exception 'Idempotency key conflict' using errcode = '23505';
    end if;
    if intent.asset_id = (select a.id from public.assets a where a.code = 'NGN')
       and not coalesce((select gate.allowed from public.can_access_ngn_services() gate limit 1), false) then
      raise exception 'NGN service requires current location verification' using errcode = '42501';
    end if;
    return intent.public_id;
  end if;

  quote := public.payment_quote(p_operation, p_asset_code, p_amount);
  if not coalesce((quote->>'enabled')::boolean, false) then
    raise exception 'Payment unavailable: %', coalesce(quote->>'reason', 'UNKNOWN') using errcode = 'P0001';
  end if;

  select * into asset
  from public.assets
  where code = upper(p_asset_code) and status = 'ACTIVE'
  limit 1;
  select id into provider
  from integration.providers
  where code = quote->>'providerCode'
    and status in ('ACTIVE', 'DEGRADED')
  order by priority, id
  limit 1;
  if provider is null then
    raise exception 'Payment provider no longer available' using errcode = 'P0001';
  end if;

  insert into payments.intents(user_id, asset_id, operation, amount, fee_amount, provider_id, status, idempotency_key)
  values(auth.uid(), asset.id, upper(p_operation), p_amount, (quote->>'feeAmount')::numeric, provider, 'CREATED', trim(p_idempotency_key))
  returning * into intent;

  if upper(p_operation) = 'WITHDRAWAL' then
    available_account := finance.ensure_user_account(auth.uid(), asset.id, 'USER_AVAILABLE');
    pending_account := finance.ensure_user_account(auth.uid(), asset.id, 'WITHDRAWAL_PENDING');
    perform finance.transfer(
      asset.id, available_account, pending_account, p_amount,
      'WITHDRAWAL_RESERVE', 'withdrawal-reserve:' || intent.public_id::text,
      'PAYMENT_INTENT', intent.public_id::text, 'Reserve funds for withdrawal', auth.uid()
    );
  end if;

  insert into eventing.domain_events(event_type, aggregate_type, aggregate_id, payload, idempotency_key)
  values(
    'PAYMENT_INTENT_CREATED', 'PAYMENT_INTENT', intent.public_id::text,
    jsonb_build_object('operation', intent.operation, 'asset', asset.code, 'amount', intent.amount, 'provider_code', quote->>'providerCode'),
    'payment-intent-created:' || intent.public_id::text
  ) on conflict(idempotency_key) do nothing;
  return intent.public_id;
end;
$function$;
create or replace function public.transfer_asset_to_email(
  p_recipient_email text,
  p_asset_code text,
  p_amount numeric,
  p_idempotency_key uuid
)
returns jsonb
language plpgsql
security definer
set search_path=''
as $function$
declare
  v_sender_id uuid:=auth.uid();
  v_recipient_id uuid;
  v_sender_country text;
  v_recipient_country text;
  v_sender_status text;
  v_recipient_status text;
  v_asset_code text:=upper(trim(coalesce(p_asset_code,'')));
  v_asset_id bigint;
  v_minor_units integer;
  v_amount numeric;
  v_sender_eligible text[];
  v_sender_policy record;
  v_source_account_id bigint;
  v_recipient_account_id bigint;
  v_source_status text;
  v_recipient_account_status text;
  v_available numeric(38,18);
  v_transfer public.asset_transfers%rowtype;
  v_transfer_public_id uuid;
  v_journal_id bigint;
  v_journal_public_id uuid;
  v_idempotency text;
  v_email text:=lower(trim(coalesce(p_recipient_email,'')));
begin
  if v_sender_id is null then
    raise exception 'Sign in before sending assets.' using errcode='28000';
  end if;
  if p_idempotency_key is null then
    raise exception 'A transfer request key is required. Please retry.' using errcode='22023';
  end if;
  if v_email='' or length(v_email)>254 or position('@' in v_email)<2 or v_email ~ '[[:space:]]' then
    raise exception 'Enter a valid recipient email address.' using errcode='22023';
  end if;
  if v_asset_code not in ('NGN','USDC') then
    raise exception 'Only real NGN and VAD ledger USDC transfers are supported. TNGN has been decommissioned.' using errcode='22023';
  end if;
  if p_amount is null or p_amount<=0 or p_amount>999999999999999999 then
    raise exception 'Enter an amount greater than zero.' using errcode='22023';
  end if;

  select u.id into v_recipient_id
  from auth.users u
  where lower(u.email)=v_email
  limit 1;
  if v_recipient_id is null then
    raise exception 'No VAD account exists for that email address. No funds were moved.' using errcode='P0002';
  end if;
  if v_recipient_id=v_sender_id then
    raise exception 'Choose another VAD account. You cannot transfer assets to yourself.' using errcode='22023';
  end if;

  if v_asset_code='NGN' and exists (
    select 1 from public.temporary_ngn_test_credit_grants g
    where g.status='ACTIVE' and g.user_id in (v_sender_id,v_recipient_id)
  ) then
    raise exception 'NGN transfers are locked while a temporary market-test credit is active. Finish testing and revoke the credit first. No funds were moved.' using errcode='42501';
  end if;

  select ua.status,case when upper(trim(coalesce(ua.country_code,''))) in ('NG','NGA','NIGERIA') then 'NG' else upper(trim(coalesce(ua.country_code,''))) end
    into v_sender_status,v_sender_country
  from public.user_accounts ua where ua.user_id=v_sender_id;
  if v_sender_status is distinct from 'ACTIVE' then
    raise exception 'Your VAD account is not active for transfers.' using errcode='42501';
  end if;
  select ua.status,case when upper(trim(coalesce(ua.country_code,''))) in ('NG','NGA','NIGERIA') then 'NG' else upper(trim(coalesce(ua.country_code,''))) end
    into v_recipient_status,v_recipient_country
  from public.user_accounts ua where ua.user_id=v_recipient_id;
  if v_recipient_status is distinct from 'ACTIVE' then
    raise exception 'The recipient account is registered but is not active for transfers.' using errcode='42501';
  end if;

  select a.id,a.minor_units into v_asset_id,v_minor_units
  from public.assets a
  where a.code=v_asset_code and a.status='ACTIVE';
  if v_asset_id is null then
    raise exception 'The selected asset is not currently available for transfers.' using errcode='42501';
  end if;
  if p_amount<>round(p_amount,v_minor_units) then
    raise exception 'The amount has too many decimal places for %.',v_asset_code using errcode='22023';
  end if;
  v_amount:=p_amount;

  select * into v_sender_policy from public.get_my_currency_policy() limit 1;
  v_sender_eligible:=coalesce(v_sender_policy.eligible_asset_codes,array[]::text[]);
  if not (v_asset_code=any(v_sender_eligible)) then
    raise exception 'Your account is not eligible to hold %.',v_asset_code using errcode='42501';
  end if;

  -- USD Coin is available to supported VAD accounts. NGN transfers require
  -- both accounts to be Nigerian and NGN to be enabled for that jurisdiction.
  if v_asset_code='NGN' then
    if not coalesce((select gate.allowed from public.can_access_ngn_services() gate limit 1),false) then
      raise exception 'NGN transfers require current location verification in Nigeria.' using errcode='42501';
    end if;
    if v_sender_country<>'NG' or v_recipient_country<>'NG' then
      raise exception 'NGN transfers are only available between eligible Nigerian VAD accounts.' using errcode='42501';
    end if;
    if not exists (
      select 1
      from public.assets a
      join public.jurisdiction_assets ja on ja.asset_id=a.id and ja.status='ACTIVE'
      join public.jurisdictions j on j.id=ja.jurisdiction_id and j.status='ACTIVE'
      where a.id=v_asset_id
        and upper(trim(j.country_code)) in ('NG','NGA','NIGERIA')
    ) then
      raise exception 'NGN transfers are disabled by jurisdiction policy.' using errcode='42501';
    end if;
  end if;

  -- Serialize retries for the same sender/request key before checking for
  -- an existing transfer, preventing concurrent network retries from double-debiting.
  perform pg_advisory_xact_lock(hashtextextended(
    'asset-transfer-request:'||v_sender_id::text||':'||p_idempotency_key::text,0
  ));

  -- Existing request-key reuse is accepted only for the same immutable transfer.
  select * into v_transfer
  from public.asset_transfers t
  where t.sender_user_id=v_sender_id and t.idempotency_key=p_idempotency_key
  for update;
  if found then
    if v_transfer.recipient_user_id<>v_recipient_id
       or v_transfer.asset_id<>v_asset_id
       or v_transfer.amount<>v_amount then
      raise exception 'This request key was already used for a different transfer. Start a new transfer.' using errcode='22023';
    end if;
    if v_transfer.status='POSTED' and v_transfer.journal_id is not null then
      select j.public_id into v_journal_public_id from finance.ledger_journals j where j.id=v_transfer.journal_id;
      return jsonb_build_object(
        'transferId',v_transfer.public_id,
        'journalId',v_journal_public_id,
        'assetCode',v_asset_code,
        'amount',v_amount,
        'status','POSTED',
        'idempotentReplay',true
      );
    end if;
    raise exception 'This transfer request is already being processed. Retry shortly using the same request.' using errcode='40001';
  end if;

  -- Serialize transfers involving these two user/asset accounts, then lock both
  -- ledger accounts so two simultaneous sends cannot spend the same available balance.
  perform pg_advisory_xact_lock(hashtextextended(
    'asset-transfer:'||least(v_sender_id::text,v_recipient_id::text)||':'||greatest(v_sender_id::text,v_recipient_id::text)||':'||v_asset_id::text,0
  ));

  select la.id,la.status into v_source_account_id,v_source_status
  from finance.ledger_accounts la
  where la.asset_id=v_asset_id and la.owner_type='USER'
    and la.owner_reference=v_sender_id::text and la.account_type='USER_AVAILABLE'
  for update;
  if v_source_account_id is null then
    raise exception 'Your % wallet is not ready for transfers. Fund it through an approved NGN/USDC funding method first.',v_asset_code using errcode='P0002';
  end if;
  if v_source_status<>'ACTIVE' then
    raise exception 'Your % wallet is frozen or closed and cannot send assets.',v_asset_code using errcode='42501';
  end if;

  insert into finance.ledger_accounts(asset_id,account_type,owner_type,owner_reference,status)
  values(v_asset_id,'USER_AVAILABLE','USER',v_recipient_id::text,'ACTIVE')
  on conflict(asset_id,account_type,owner_type,owner_reference) do nothing;

  select la.id,la.status into v_recipient_account_id,v_recipient_account_status
  from finance.ledger_accounts la
  where la.asset_id=v_asset_id and la.owner_type='USER'
    and la.owner_reference=v_recipient_id::text and la.account_type='USER_AVAILABLE'
  for update;
  if v_recipient_account_id is null then
    raise exception 'The recipient % wallet could not be prepared. No funds were moved.',v_asset_code using errcode='P0002';
  end if;
  if v_recipient_account_status<>'ACTIVE' then
    raise exception 'The recipient % wallet is frozen or closed. No funds were moved.',v_asset_code using errcode='42501';
  end if;

  v_available:=finance.account_balance(v_source_account_id);
  if v_available<v_amount then
    raise exception 'Insufficient available % balance. No funds were moved.',v_asset_code using errcode='22023';
  end if;

  insert into public.asset_transfers(
    sender_user_id,recipient_user_id,asset_id,amount,idempotency_key,status
  ) values(v_sender_id,v_recipient_id,v_asset_id,v_amount,p_idempotency_key,'PROCESSING')
  returning public_id into v_transfer_public_id;

  v_idempotency:='USER_ASSET_TRANSFER:'||v_sender_id::text||':'||p_idempotency_key::text;
  v_journal_id:=finance.transfer(
    v_asset_id,
    v_source_account_id,
    v_recipient_account_id,
    v_amount,
    'USER_ASSET_TRANSFER',
    v_idempotency,
    'USER_ASSET_TRANSFER',
    v_transfer_public_id::text,
    'VAD account-to-account transfer',
    v_sender_id
  );

  select j.public_id into v_journal_public_id
  from finance.ledger_journals j where j.id=v_journal_id;

  update public.asset_transfers
  set status='POSTED',journal_id=v_journal_id
  where public_id=v_transfer_public_id;

  return jsonb_build_object(
    'transferId',v_transfer_public_id,
    'journalId',v_journal_public_id,
    'assetCode',v_asset_code,
    'amount',v_amount,
    'status','POSTED',
    'idempotentReplay',false
  );
end;
$function$;
select pg_notify('pgrst','reload schema');
commit;
