create or replace function public.admin_set_discovered_event_candidate_status(
  p_candidate_public_id uuid,p_status text,p_reason text
)
returns boolean
language plpgsql
security definer
set search_path=''
as $function$
declare
  v_status text:=upper(btrim(coalesce(p_status,'')));
  v_category text;
  v_title text;
begin
  if auth.uid() is null or not private.has_permission('markets.manage') then
    raise exception 'Market management permission required' using errcode='42501';
  end if;
  if v_status not in ('REVIEWED','IGNORED') or char_length(btrim(coalesce(p_reason,'')))<3 then
    raise exception 'Choose Reviewed or Ignored and provide a reason.' using errcode='22023';
  end if;
  update market.discovered_event_candidates
  set status=v_status,reviewed_by=auth.uid(),reviewed_at=statement_timestamp(),updated_at=statement_timestamp()
  where candidate_public_id=p_candidate_public_id
  returning category_code,title into v_category,v_title;
  if not found then raise exception 'Discovered event candidate not found.' using errcode='P0002'; end if;
  insert into audit.records(actor_user_id,actor_type,action,resource_type,resource_id,reason,metadata)
  values(auth.uid(),'ADMIN','DISCOVERED_EVENT_CANDIDATE_STATUS_UPDATED','DISCOVERED_EVENT_CANDIDATE',
    p_candidate_public_id::text,btrim(p_reason),jsonb_build_object('status',v_status,'category_code',v_category,'title',v_title));
  return true;
end;
$function$;
