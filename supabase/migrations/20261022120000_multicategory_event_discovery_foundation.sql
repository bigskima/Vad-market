create or replace function public.admin_list_discovered_event_candidates(
  p_category_code text default null,p_limit integer default 50
)
returns table(
  candidate_public_id uuid,
  source_code text,
  source_name text,
  category_code text,
  category_name text,
  region_code text,
  title text,
  summary text,
  source_url text,
  source_published_at timestamptz,
  status text,
  first_seen_at timestamptz,
  last_seen_at timestamptz
)
language plpgsql
stable
security definer
set search_path=''
as $function$
declare v_category text:=upper(nullif(btrim(coalesce(p_category_code,'')),''));
begin
  if auth.uid() is null or not private.has_permission('markets.manage') then
    raise exception 'Market management permission required' using errcode='42501';
  end if;
  return query
  select d.candidate_public_id,d.source_code,s.name,d.category_code,c.name,d.region_code,
         d.title,d.summary,d.source_url,d.source_published_at,d.status,d.first_seen_at,d.last_seen_at
  from market.discovered_event_candidates d
  join market.event_discovery_sources s on s.code=d.source_code
  join market.guided_categories c on c.code=d.category_code
  where (v_category is null or d.category_code=v_category)
  order by case d.status when 'DISCOVERED' then 0 when 'REVIEWED' then 1 when 'DRAFTED' then 2 else 3 end,
           d.last_seen_at desc
  limit least(greatest(coalesce(p_limit,50),1),100);
end;
$function$;
revoke all on function public.admin_list_discovered_event_candidates(text,integer) from public,anon;
