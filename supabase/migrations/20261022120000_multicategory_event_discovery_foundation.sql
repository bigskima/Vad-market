create or replace function public.internal_upsert_discovered_event_candidates(p_candidates jsonb)
returns jsonb
language plpgsql
security definer
set search_path=''
as $function$
declare
  v_item jsonb;
  v_source text;
  v_category text;
  v_region text;
  v_title text;
  v_summary text;
  v_url text;
  v_external_id text;
  v_hash text;
  v_query text;
  v_published timestamptz;
  v_payload jsonb;
  v_processed integer:=0;
  v_inserted integer:=0;
  v_updated integer:=0;
  v_existing boolean;
  v_id uuid;
begin
  if coalesce(auth.role(),'')<>'service_role' then
    raise exception 'Service role required' using errcode='42501';
  end if;
  if jsonb_typeof(coalesce(p_candidates,'null'::jsonb))<>'array'
     or jsonb_array_length(p_candidates)>200 then
    raise exception 'Candidate input must be an array with no more than 200 items.' using errcode='22023';
  end if;

  for v_item in select value from jsonb_array_elements(p_candidates)
  loop
    v_source:=upper(btrim(coalesce(v_item->>'source_code','')));
    v_category:=upper(btrim(coalesce(v_item->>'category_code','')));
    v_region:=upper(btrim(coalesce(v_item->>'region_code','GLOBAL')));
    v_title:=btrim(coalesce(v_item->>'title',''));
    v_summary:=left(btrim(coalesce(v_item->>'summary','')),2000);
    v_url:=btrim(coalesce(v_item->>'source_url',''));
    v_external_id:=left(btrim(coalesce(v_item->>'external_id','')),500);
    v_query:=left(btrim(coalesce(v_item->>'discovery_query','')),300);
    v_payload:=case when jsonb_typeof(v_item->'candidate_payload')='object' then v_item->'candidate_payload' else '{}'::jsonb end;
    v_published:=null;
    if nullif(v_item->>'source_published_at','') is not null then
      begin v_published:=(v_item->>'source_published_at')::timestamptz; exception when others then v_published:=null; end;
    end if;
    if char_length(v_title) not between 8 and 500
       or v_url !~ '^https://'
       or v_external_id=''
       or v_region !~ '^[A-Z0-9_-]{2,24}$'
       or not exists(select 1 from market.event_discovery_sources s where s.code=v_source and s.status in ('ACTIVE','DEGRADED'))
       or not exists(select 1 from market.guided_categories c where c.code=v_category and c.status='ACTIVE') then
      continue;
    end if;
    v_hash:=md5(lower(regexp_replace(regexp_replace(coalesce(nullif(v_url,''),v_external_id), '[?#].*$', '', 'g'), '/+$','')));
    select exists(select 1 from market.discovered_event_candidates d where d.category_code=v_category and d.canonical_hash=v_hash) into v_existing;
    insert into market.discovered_event_candidates(
      source_code,category_code,region_code,title,summary,source_url,external_id,
      canonical_hash,source_published_at,discovery_query,candidate_payload,last_seen_at,updated_at
    ) values (
      v_source,v_category,v_region,v_title,nullif(v_summary,''),v_url,v_external_id,
      v_hash,v_published,nullif(v_query,''),v_payload,statement_timestamp(),statement_timestamp()
    )
    on conflict(category_code,canonical_hash) do update set
      source_code=excluded.source_code,
      region_code=excluded.region_code,
      title=excluded.title,
      summary=coalesce(excluded.summary,market.discovered_event_candidates.summary),
      source_url=excluded.source_url,
      external_id=excluded.external_id,
      source_published_at=coalesce(excluded.source_published_at,market.discovered_event_candidates.source_published_at),
      discovery_query=coalesce(excluded.discovery_query,market.discovered_event_candidates.discovery_query),
      candidate_payload=excluded.candidate_payload,
      last_seen_at=statement_timestamp(),
      updated_at=statement_timestamp()
    returning candidate_public_id into v_id;
    v_processed:=v_processed+1;
    if v_existing then v_updated:=v_updated+1; else v_inserted:=v_inserted+1; end if;
  end loop;
  return jsonb_build_object('processed',v_processed,'inserted',v_inserted,'updated',v_updated);
end;
$function$;
revoke all on function public.internal_upsert_discovered_event_candidates(jsonb) from public,anon,authenticated;
