create or replace function public.admin_upsert_event_discovery_source(
  p_code text,
  p_name text,
  p_adapter_code text,
  p_endpoint text,
  p_category_codes text[] default array['*']::text[],
  p_region_codes text[] default array['*']::text[],
  p_status text default 'DISABLED',
  p_priority integer default 100,
  p_daily_request_limit integer default 100,
  p_cache_seconds integer default 300,
  p_config jsonb default '{}'::jsonb,
  p_reason text default 'Updated event discovery source configuration'
)
returns text
language plpgsql
security definer
set search_path=''
as $function$
declare
  v_code text:=upper(btrim(coalesce(p_code,'')));
  v_name text:=btrim(coalesce(p_name,''));
  v_adapter text:=upper(btrim(coalesce(p_adapter_code,'')));
  v_endpoint text:=btrim(coalesce(p_endpoint,''));
  v_status text:=upper(btrim(coalesce(p_status,'DISABLED')));
  v_categories text[]:=coalesce(p_category_codes,array['*']::text[]);
  v_regions text[]:=coalesce(p_region_codes,array['*']::text[]);
  v_host text;
begin
  if auth.uid() is null or not private.has_permission('markets.manage') then
    raise exception 'Market management permission required' using errcode='42501';
  end if;
  if v_code !~ '^[A-Z][A-Z0-9_]{1,79}$'
     or char_length(v_name) not between 2 and 160
     or v_adapter not in ('GDELT_DOC_V2','RSS_ATOM')
     or v_status not in ('ACTIVE','DISABLED','DEGRADED')
     or char_length(btrim(coalesce(p_reason,'')))<3
     or jsonb_typeof(coalesce(p_config,'{}'::jsonb))<>'object' then
    raise exception 'Invalid event-discovery source configuration.' using errcode='22023';
  end if;
  if v_endpoint !~ '^https://' or position('@' in split_part(regexp_replace(v_endpoint,'^https://',''), '/',1))>0 then
    raise exception 'Event-discovery sources must use an HTTPS endpoint without embedded credentials.' using errcode='22023';
  end if;
  v_host:=lower(split_part(regexp_replace(v_endpoint,'^https://',''), '/',1));
  if v_host in ('localhost','127.0.0.1','0.0.0.0','169.254.169.254')
     or v_host !~ '^[a-z0-9.-]+\.[a-z]{2,}(:443)?$'
     or v_host ~ '(^|\.)((localhost)|(local)|(internal))$'
     or v_host ~ '^([0-9]{1,3}\.){3}[0-9]{1,3}(:443)?$' then
    raise exception 'The configured source host is not allowed.' using errcode='22023';
  end if;
  if v_adapter='GDELT_DOC_V2' and v_endpoint<>'https://api.gdeltproject.org/api/v2/doc/doc' then
    raise exception 'GDELT source must use the approved public GDELT document API endpoint.' using errcode='22023';
  end if;
  if cardinality(v_categories)=0 or cardinality(v_regions)=0
     or exists(
       select 1 from unnest(v_categories) c
       where c<>'*' and not exists(
         select 1 from market.guided_categories gc where gc.code=upper(btrim(c)) and gc.status='ACTIVE'
       )
     ) then
    raise exception 'Choose active VAD categories or the all-categories wildcard.' using errcode='22023';
  end if;
  if exists(select 1 from unnest(v_regions) r where r<>'*' and r !~ '^[A-Z0-9_-]{2,24}$') then
    raise exception 'Region codes must use short stable codes or the wildcard.' using errcode='22023';
  end if;

  insert into market.event_discovery_sources(
    code,name,adapter_code,endpoint,category_codes,region_codes,status,priority,
    daily_request_limit,cache_seconds,config,updated_by
  ) values (
    v_code,v_name,v_adapter,v_endpoint,
    array(select distinct case when btrim(c)='*' then '*' else upper(btrim(c)) end from unnest(v_categories) c),
    array(select distinct case when btrim(r)='*' then '*' else upper(btrim(r)) end from unnest(v_regions) r),
    v_status,least(greatest(coalesce(p_priority,100),0),10000),
    least(greatest(coalesce(p_daily_request_limit,100),1),10000),
    least(greatest(coalesce(p_cache_seconds,300),30),86400),
    coalesce(p_config,'{}'::jsonb),auth.uid()
  )
  on conflict(code) do update set
    name=excluded.name,
    adapter_code=excluded.adapter_code,
    endpoint=excluded.endpoint,
    category_codes=excluded.category_codes,
    region_codes=excluded.region_codes,
    status=excluded.status,
    priority=excluded.priority,
    daily_request_limit=excluded.daily_request_limit,
    cache_seconds=excluded.cache_seconds,
    config=excluded.config,
    updated_by=auth.uid(),
    updated_at=statement_timestamp();

  insert into audit.records(actor_user_id,actor_type,action,resource_type,resource_id,reason,metadata)
  values(auth.uid(),'ADMIN','EVENT_DISCOVERY_SOURCE_UPSERTED','EVENT_DISCOVERY_SOURCE',v_code,
    btrim(p_reason),jsonb_build_object('adapter_code',v_adapter,'endpoint',v_endpoint,'status',v_status,'category_codes',to_jsonb(v_categories),'region_codes',to_jsonb(v_regions)));
  return v_code;
end;
$function$;
